  id_pedido        bigint not null references public.pedidos (id_pedido),
  id_factura       bigint references public.facturas (id_factura),
  id_bodega        bigint not null references public.bodegas (id_bodega),
  via_despacho     text,
  observacion      text,
  estado           text not null default 'emitido' check (estado in ('emitido', 'anulado')),
  motivo_anulacion text,
  fecha_anulacion  timestamptz,
  usuario_creacion text not null default 'Admin',
  creado_en        timestamptz not null default now()
