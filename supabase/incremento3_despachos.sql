  id_detalle_despacho  bigint generated by default as identity primary key,
  id_despacho          bigint not null references public.despachos (id_despacho) on delete cascade,
  id_detalle_pedido    bigint not null references public.detalle_pedidos (id_detalle_pedido),
  cantidad             integer not null check (cantidad > 0),
  precio_unitario      integer not null check (precio_unitario >= 0),
  descuento_porcentaje numeric(5,2) not null default 0 check (descuento_porcentaje between 0 and 100),
  constraint detalle_despachos_linea_uk unique (id_despacho, id_detalle_pedido)
