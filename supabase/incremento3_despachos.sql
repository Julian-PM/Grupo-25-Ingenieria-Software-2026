-- Cantidad pedida, anulada, despachada y pendiente por línea de pedido.
-- Base de RF-042/043, RF-053 y RF-054.
create or replace view public.v_detalle_pedido_pendiente
with (security_invoker = true) as
select p.id_pedido,
       p.numero_pedido,
       p.fecha_pedido,
       p.fecha_entrega,
       p.estado,
       p.cliente_asociado  as id_cliente,
       c.nombre            as cliente,
       p.vendedor_asociado as id_vendedor,
       v.nombre            as vendedor,
       d.id_detalle_pedido,
       pv.id_variante,
       pv.id_producto,
       pr.descripcion      as producto,
       pv.id_color,
       co.descripcion      as color,
       pv.id_talla,
       t.talla,
       d.cantidad          as cantidad_pedida,
       d.cantidad_anulada,
       coalesce(x.despachada, 0)                                  as cantidad_despachada,
       d.cantidad - d.cantidad_anulada - coalesce(x.despachada, 0) as cantidad_pendiente
  from detalle_pedidos d
  join pedidos p             on p.id_pedido = d.id_pedido
  join producto_variantes pv on pv.id_variante = d.id_variante
  left join productos pr     on pr.id_producto = pv.id_producto
  left join colores co       on co.id_color = pv.id_color
  left join tallas t         on t.id_talla = pv.id_talla
  left join clientes c       on c.id_cliente = p.cliente_asociado
  left join vendedores v     on v.id_vendedor = p.vendedor_asociado
  left join lateral (
    select sum(dd.cantidad) as despachada
      from detalle_despachos dd
      join despachos de on de.id_despacho = dd.id_despacho
     where dd.id_detalle_pedido = d.id_detalle_pedido and de.estado = 'emitido'
  ) x on true
 where p.estado <> 'anulado';

-- RF-042/043: productos pendientes de despacho y cuánto stock hay para ellos.
-- stock_disponible es el total de todas las bodegas; si varios pedidos piden
-- la misma variante, lo comparten.
create or replace view public.v_pendientes_despacho
with (security_invoker = true) as
select dp.*,
       coalesce(s.stock, 0)                            as stock_disponible,
       least(dp.cantidad_pendiente, coalesce(s.stock, 0)) as cantidad_lista_para_despacho
  from v_detalle_pedido_pendiente dp
  left join (
    select id_producto, id_talla, id_color, sum(cantidad) as stock
      from inventario group by id_producto, id_talla, id_color
  ) s on s.id_producto = dp.id_producto and s.id_talla = dp.id_talla and s.id_color = dp.id_color
 where dp.cantidad_pendiente > 0;

-- RF-045 a RF-050: una fila por producto despachado, con pedido, cliente,
-- vendedor, factura, precio y descuento.
create or replace view public.v_despachos_detalle
with (security_invoker = true) as
select de.id_despacho,
       de.numero_guia,
       de.fecha,
       date_trunc('month', de.fecha)::date as mes,
       de.estado,
       de.id_bodega,
       b.descripcion          as bodega,
       de.via_despacho,
       p.id_pedido,
       p.numero_pedido,
       p.cliente_asociado     as id_cliente,
       c.nombre               as cliente,
       p.vendedor_asociado    as id_vendedor,
       v.nombre               as vendedor,
       de.id_factura,
       f.numero_factura,
       dd.id_detalle_despacho,
       pv.id_variante,
       pv.id_producto,
       pr.descripcion         as producto,
       co.descripcion         as color,
       t.talla,
       dd.cantidad,
       dd.precio_unitario,
       dd.descuento_porcentaje,
       dd.cantidad * dd.precio_unitario                                    as subtotal_bruto,
       round(dd.cantidad * dd.precio_unitario * dd.descuento_porcentaje / 100) as monto_descuento,
       dd.cantidad * dd.precio_unitario
         - round(dd.cantidad * dd.precio_unitario * dd.descuento_porcentaje / 100) as subtotal_neto
  from detalle_despachos dd
  join despachos de          on de.id_despacho = dd.id_despacho
  join pedidos p             on p.id_pedido = de.id_pedido
  join detalle_pedidos d     on d.id_detalle_pedido = dd.id_detalle_pedido
  join producto_variantes pv on pv.id_variante = d.id_variante
  left join productos pr     on pr.id_producto = pv.id_producto
  left join colores co       on co.id_color = pv.id_color
  left join tallas t         on t.id_talla = pv.id_talla
  left join clientes c       on c.id_cliente = p.cliente_asociado
  left join vendedores v     on v.id_vendedor = p.vendedor_asociado
  left join facturas f       on f.id_factura = de.id_factura
  left join bodegas b        on b.id_bodega = de.id_bodega;

-- RF-051: pedidos y despachos por mes.
create or replace view public.v_pedidos_despachos_mensual
with (security_invoker = true) as
with ped as (
  select date_trunc('month', p.fecha_pedido)::date as mes,
         count(distinct p.id_pedido)                as pedidos,
         coalesce(sum(d.cantidad - d.cantidad_anulada), 0) as unidades_pedidas
    from pedidos p
    left join detalle_pedidos d on d.id_pedido = p.id_pedido
   where p.estado <> 'anulado'
   group by 1
), des as (
  select date_trunc('month', de.fecha)::date as mes,
         count(distinct de.id_despacho)       as despachos,
         coalesce(sum(dd.cantidad), 0)        as unidades_despachadas
    from despachos de
    left join detalle_despachos dd on dd.id_despacho = de.id_despacho
   where de.estado = 'emitido'
   group by 1
)
select coalesce(ped.mes, des.mes)              as mes,
       coalesce(ped.pedidos, 0)                as pedidos,
       coalesce(ped.unidades_pedidas, 0)       as unidades_pedidas,
       coalesce(des.despachos, 0)              as despachos,
       coalesce(des.unidades_despachadas, 0)   as unidades_despachadas
  from ped full outer join des on des.mes = ped.mes;

-- RF-053: stock, defectuosos y unidades comprometidas en pedidos.
-- unidades_comprometidas es el total pendiente de todos los pedidos para
-- esa variante (no distingue bodega).
create or replace view public.v_inventario_analisis
with (security_invoker = true) as
select i.id_inventario,
       i.id_bodega,
       b.descripcion          as bodega,
       i.id_producto,
       pr.descripcion         as producto,
       i.id_talla,
       t.talla,
       i.id_color,
       co.descripcion         as color,
       i.cantidad             as stock_disponible,
       i.cantidad_defectuosa,
       coalesce(pp.pendiente, 0)       as unidades_comprometidas,
       coalesce(pp.pendiente, 0) > 0   as asociado_a_pedidos,
       i.fecha_actualizacion
  from inventario i
  left join bodegas b    on b.id_bodega = i.id_bodega
  left join productos pr on pr.id_producto = i.id_producto
  left join tallas t     on t.id_talla = i.id_talla
  left join colores co   on co.id_color = i.id_color
  left join (
    select id_producto, id_talla, id_color, sum(cantidad_pendiente) as pendiente
      from v_detalle_pedido_pendiente
     where cantidad_pendiente > 0
     group by id_producto, id_talla, id_color
  ) pp on pp.id_producto = i.id_producto and pp.id_talla = i.id_talla and pp.id_color = i.id_color;

-- RF-054: productos en proceso = cortes aún no ingresados a bodega.
create or replace view public.v_productos_en_proceso
with (security_invoker = true) as
select co.id_corte,
       co.fecha_corte,
       co.cortador,
       co.material_usado,
       co.cantidad,
       co.observaciones,
       co.producto_asociado as id_producto,
       pr.descripcion       as producto,
       cl.descripcion       as color,
       t.talla,
       co.id_pedido,
       p.numero_pedido,
       c.nombre             as cliente,
       (current_date - co.fecha_corte) as dias_en_proceso
  from cortes co
  left join productos pr on pr.id_producto = co.producto_asociado
  left join colores cl   on cl.id_color = pr.color
  left join tallas t     on t.id_talla = pr.talla
  left join pedidos p    on p.id_pedido = co.id_pedido
  left join clientes c   on c.id_cliente = p.cliente_asociado
 where co.estado = 'pendiente';

-- RF-052 y RF-055: producción terminada (ingresos de guías de corte a bodega).
create or replace view public.v_produccion_terminada
with (security_invoker = true) as
select m.id_movimiento,
       m.fecha,
       m.fecha::date       as dia,
       m.id_corte,
       m.id_bodega,
       b.descripcion       as bodega,
       m.id_producto,
       pr.descripcion      as producto,
       m.id_talla,
       t.talla,
       m.id_color,
       co.descripcion      as color,
       m.cantidad
  from movimientos_inventario m
  left join bodegas b    on b.id_bodega = m.id_bodega
  left join productos pr on pr.id_producto = m.id_producto
  left join tallas t     on t.id_talla = m.id_talla
  left join colores co   on co.id_color = m.id_color
 where m.tipo = 'entrada_corte';

commit;
